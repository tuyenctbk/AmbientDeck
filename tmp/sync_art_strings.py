def escape_xml_text(text):
    text = text.replace("&", "&amp;")
    text = text.replace("<", "&lt;")
    text = text.replace(">", "&gt;")
    text = text.replace("'", "\\'")
    text = text.replace('"', '\\"')
    return text

res_dir = "/app/src/main/res"

def update_file(filepath, locale_key):
    if not os.path.exists(filepath):
        print(f"Skipping missing: {filepath}")
        return
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    # Find where </resources> is
    idx = content.rfind("</resources>")
    if idx == -1:
        print(f"Error: no </resources> in {filepath}")
        return

    added = []
    for key, trans_dict in NEW_STRINGS.items():
        if f'name="{key}"' in content:
            continue
        val = trans_dict.get(locale_key, trans_dict.get("en", ""))
        escaped_val = escape_xml_text(val)
        added.append(f'    <string name="{key}">{escaped_val}</string>')

    if added:
        new_block = "\n" + "\n".join(added) + "\n"
        new_content = content[:idx] + new_block + content[idx:]
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(new_content)
        print(f"Updated {filepath} with {len(added)} strings.")
    else:
        print(f"No new strings needed for {filepath}")

